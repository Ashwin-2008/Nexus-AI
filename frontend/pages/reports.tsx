import React, { useEffect, useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import {
  AlertTriangle,
  ArrowRight,
  CheckCircle2,
  Download,
  FileArchive,
  FileSpreadsheet,
  FileText,
  FileType2,
  RefreshCw,
  Trash2,
} from 'lucide-react'
import {
  ReportMetadata,
  deleteReport,
  downloadReport,
  listReports,
} from '@/src/api'
import { EmptyState, PageHeader, StatCard, StatusBadge, formatDate, timeAgo } from '@/components/nx'
import { Button } from '@/components/ui/button'
import { Card } from '@/components/ui/card'
import { Select } from '@/components/ui/input'

type FormatFilter = 'all' | 'pdf' | 'docx' | 'xlsx' | 'csv' | 'md'

function formatIcon(format: string) {
  if (format === 'csv' || format === 'xlsx') return <FileSpreadsheet />
  if (format === 'pdf') return <FileText />
  if (format === 'docx') return <FileType2 />
  if (format === 'md' || format === 'markdown') return <FileArchive />
  return <FileText />
}

function formatLabel(format: string): string {
  if (format === 'markdown') return 'markdown'
  return format.toUpperCase()
}

export default function Reports() {
  const [reports, setReports] = useState<ReportMetadata[]>([])
  const [filter, setFilter] = useState<FormatFilter>('all')
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState<string | null>(null)
  const [message, setMessage] = useState<string | null>(null)
  const [busyId, setBusyId] = useState<string | null>(null)

  async function load() {
    setLoading(true)
    try {
      setReports(await listReports())
      setError(null)
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'Unable to load reports')
    } finally {
      setLoading(false)
    }
  }

  useEffect(() => {
    void load()
  }, [])

  const visible = useMemo(
    () => reports.filter((report) => filter === 'all' || report.file_format === filter || (filter === 'md' && report.file_format === 'markdown')),
    [filter, reports],
  )

  const completed = reports.filter((report) => report.status === 'completed').length
  const failed = reports.filter((report) => report.status === 'failed').length
  const formats = new Set(reports.map((report) => report.file_format)).size

  async function handleDownload(report: ReportMetadata) {
    setBusyId(report.id)
    setError(null)
    try {
      await downloadReport(report)
      setMessage(`${report.title} downloaded.`)
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'Download failed')
    } finally {
      setBusyId(null)
    }
  }

  async function handleDelete(report: ReportMetadata) {
    if (!window.confirm(`Delete ${report.title}? The stored artifact will also be removed.`)) return
    setBusyId(report.id)
    setError(null)
    try {
      await deleteReport(report.id)
      setReports((current) => current.filter((item) => item.id !== report.id))
      setMessage(`${report.title} deleted.`)
    } catch (caught) {
      setError(caught instanceof Error ? caught.message : 'Unable to delete report')
    } finally {
      setBusyId(null)
    }
  }

  return (
    <div className="nx-stack" style={{ gap: 22 }}>
      <PageHeader
        eyebrow="Deliverables"
        title="Reports"
        description="Persisted report artifacts generated by specialist agents or exported through the reports API. Downloads are authenticated and organization-scoped."
        actions={
          <>
            <Button variant="secondary" onClick={() => void load()} loading={loading}><RefreshCw size={14} /> Refresh</Button>
            <Link to="/app/agent-control-center"><Button><FileText size={14} /> Generate with an agent</Button></Link>
          </>
        }
      />

      <section className="nx-grid nx-grid--4">
        <StatCard icon={<FileText />} label="Reports" value={reports.length} meta="Organization artifacts" />
        <StatCard icon={<CheckCircle2 />} label="Completed" value={completed} meta="Ready to download" accent="green" progress={reports.length ? (completed / reports.length) * 100 : 0} />
        <StatCard icon={<AlertTriangle />} label="Failed" value={failed} meta="Metadata retained" accent="pink" />
        <StatCard icon={<FileArchive />} label="Formats" value={formats} meta="Distinct output types" accent="violet" />
      </section>

      {error && <div className="nx-error">{error}</div>}
      {message && <div className="nx-success">{message}</div>}

      <Card
        title="Report library"
        subtitle={`${visible.length} of ${reports.length} artifacts`}
        actions={
          <Select value={filter} onChange={(event) => setFilter(event.target.value as FormatFilter)} style={{ width: 150, minHeight: 34 }}>
            <option value="all">All formats</option>
            <option value="pdf">PDF</option>
            <option value="docx">DOCX</option>
            <option value="xlsx">XLSX</option>
            <option value="csv">CSV</option>
            <option value="md">Markdown</option>
          </Select>
        }
        flush
      >
        {loading ? (
          <div className="nx-stack" style={{ padding: '0 22px 22px' }}>
            <div className="nx-skeleton" style={{ height: 44 }} />
            <div className="nx-skeleton" style={{ height: 44 }} />
            <div className="nx-skeleton" style={{ height: 44 }} />
          </div>
        ) : visible.length === 0 ? (
          <EmptyState
            icon={<FileText />}
            title={reports.length ? 'No reports match this format' : 'No reports yet'}
            description={reports.length ? 'Choose another output format.' : 'Run a report-oriented agent task or export a report to create a durable artifact.'}
            action={<Link to="/app/agent-control-center"><Button size="sm">Open agent control center</Button></Link>}
          />
        ) : (
          <div className="nx-table__wrap" style={{ border: 0, borderRadius: 0, background: 'transparent' }}>
            <table className="nx-table">
              <thead>
                <tr>
                  <th>Report</th>
                  <th>Format</th>
                  <th>Status</th>
                  <th>Created</th>
                  <th style={{ textAlign: 'right' }}>Actions</th>
                </tr>
              </thead>
              <tbody>
                {visible.map((report) => (
                  <tr key={report.id}>
                    <td>
                      <span className="nx-row" style={{ gap: 10 }}>
                        <span className="nx-list-item__icon" style={{ width: 34, height: 34 }}>{formatIcon(report.file_format)}</span>
                        <span style={{ minWidth: 0 }}>
                          <span className="nx-small" style={{ display: 'block', fontWeight: 700 }}>{report.title}</span>
                          <span className="nx-xs nx-muted" style={{ display: 'block' }}>
                            {report.report_type} · {formatDate(report.created_at)} · {timeAgo(report.created_at)}
                          </span>
                        </span>
                      </span>
                    </td>
                    <td><span className="nx-badge">{formatLabel(report.file_format)}</span></td>
                    <td><StatusBadge status={report.status} /></td>
                    <td className="nx-xs nx-muted nx-nowrap">{formatDate(report.created_at)}</td>
                    <td>
                      <div className="nx-row" style={{ justifyContent: 'flex-end', gap: 6 }}>
                        {report.execution_id && (
                          <Link to="/app/agent-control-center" className="nx-btn nx-btn--ghost nx-btn--sm" title="View the execution that generated this report">
                            Execution <ArrowRight size={12} />
                          </Link>
                        )}
                        <Button size="sm" variant="outline" onClick={() => void handleDownload(report)} loading={busyId === report.id} disabled={!report.storage_key}>
                          <Download size={12} /> Download
                        </Button>
                        <Button size="sm" variant="ghost" onClick={() => void handleDelete(report)} loading={busyId === report.id} aria-label={`Delete ${report.title}`} style={{ color: 'var(--nx-danger)' }}>
                          <Trash2 size={13} />
                        </Button>
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </div>
  )
}
